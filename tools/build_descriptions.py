"""Assemble the published descriptions, including all five reading sections.

Edit data/descriptions.json. Independently reviewed notices take precedence.
These checks verify coverage, structure and references, not historical accuracy.
Run python tools/build_descriptions.py [--check].
"""
import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = {'fascination', 'legendes', 'anomalies', 'naturelle', 'reliques'}
PARTS = ['Comportement', 'Habitat', 'Alimentation', 'Intelligence', 'Reproduction', 'Prédateurs']

def bundle(path):
    text = path.read_text(encoding='utf-8')
    return json.loads(text[text.index('{'):text.rindex('}') + 1])

def paragraphs(value):
    if isinstance(value, str):
        return [value]
    assert isinstance(value, list) and value, 'Nonempty paragraphs required'
    assert all(isinstance(p, str) for p in value), 'Paragraphs must be strings'
    return value

def validate(entries, expected, reviewed):
    assert set(entries) <= expected, 'Unknown creature in descriptions'
    assert set(reviewed) | set(entries) == expected, 'Every creature needs a description'
    seen = {}
    for slug, entry in entries.items():
        assert isinstance(entry.get('description'), str) and entry['description'].strip(), slug
        sections = entry['sections']
        assert set(sections) == SECTIONS, f'{slug}: all five sections required'
        texts = [entry['description']]
        for key in ['fascination', 'legendes', 'anomalies', 'reliques']:
            texts.extend(paragraphs(sections[key]))
        assert len(paragraphs(sections['fascination'])) >= 2, slug
        natural = sections['naturelle']
        texts.extend(paragraphs(natural['lead']))
        assert [part['title'] for part in natural['parts']] == PARTS, f'{slug}: six natural-history parts required'
        for part in natural['parts']:
            texts.extend(paragraphs(part['body']))
        references = [source['id'] for source in entry['sources']]
        assert references and len(references) == len(set(references)), f'{slug}: missing or duplicate references'
        for source in entry['sources']:
            assert type(source['id']) is int and source['id'] > 0, slug
            assert source['title'].strip(), slug
            url = urlsplit(source['url'])
            assert url.scheme in ('http', 'https') and url.hostname and not url.username, slug
        for text in texts:
            assert isinstance(text, str) and len(text.strip()) > 30, f'{slug}: empty or fragmentary text'
            assert not re.search(r'<[^>]*>|\b(?:TODO|TBD|LOREM IPSUM)\b', text, re.I), slug
            assert set(map(int, re.findall(r'\[(\d+)\]', text))) <= set(references), f'{slug}: unresolved reference'
            normalized = re.sub(r'\s+', ' ', re.sub(r'\[\d+\]', '', text)).strip().casefold()
            if len(normalized) > 120:
                assert normalized not in seen, f'Duplicate paragraph: {slug} / {seen.get(normalized)}'
                seen[normalized] = slug

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    entries = json.loads((ROOT/'data/descriptions.json').read_text(encoding='utf-8'))
    catalog = bundle(ROOT/'js/creatures-data.js')['creatures']
    reviewed = bundle(ROOT/'js/notices.js')
    expected = {entry['slug'] for entry in catalog}
    validate(entries, expected, reviewed)
    content = '// Generated by tools/build_descriptions.py. Edit data/descriptions.json.\n'
    content += 'window.FF_DESCRIPTIONS = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ';\n'
    target = ROOT/'js/descriptions.js'
    if args.check:
        assert target.read_text(encoding='utf-8') == content, 'Description bundle is stale'
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
    print(f'{len(entries)} expanded descriptions; {len(reviewed)} reviewed notices; {len(expected)} creatures covered.')

if __name__ == '__main__':
    main()
