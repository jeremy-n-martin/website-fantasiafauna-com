"""Build short presentations without promoting unfinished long articles.

Edit data/descriptions.json. Long reviewed notices always take precedence.
Run python tools/build_descriptions.py [--check].
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def bundle(path):
    text = path.read_text(encoding='utf-8')
    return json.loads(text[text.index('{'):text.rindex('}') + 1])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    entries = json.loads((ROOT/'data/descriptions.json').read_text(encoding='utf-8'))
    catalog = bundle(ROOT/'js/creatures-data.js')['creatures']
    reviewed = bundle(ROOT/'js/notices.js')
    expected = {entry['slug'] for entry in catalog}
    assert set(entries) <= expected, 'Unknown creature in short descriptions'
    assert set(reviewed) | set(entries) == expected, 'Every creature needs a description'
    seen = set()
    for slug, entry in entries.items():
        assert isinstance(entry.get('description'), str) and entry['description'].strip(), slug
        assert set(entry['sections']) == {'fascination'}, slug
        paragraphs = entry['sections']['fascination']
        assert len(paragraphs) >= 2, slug
        references = {source['id'] for source in entry['sources']}
        for paragraph in [entry['description'], *paragraphs]:
            assert isinstance(paragraph, str) and len(paragraph.strip()) > 30, slug
            assert not re.search(r'<[^>]*>|\b(?:TODO|TBD|LOREM IPSUM)\b', paragraph, re.I), slug
            assert set(map(int, re.findall(r'\[(\d+)\]', paragraph))) <= references, slug
            normalized = re.sub(r'\s+', ' ', paragraph).strip().casefold()
            assert normalized not in seen, f'Duplicate paragraph: {slug}'
            seen.add(normalized)
    content = '// Generated by tools/build_descriptions.py. Edit data/descriptions.json.\n'
    content += 'window.FF_DESCRIPTIONS = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ';\n'
    target = ROOT/'js/descriptions.js'
    if args.check:
        assert target.read_text(encoding='utf-8') == content, 'Short-description bundle is stale'
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
    print(f'{len(entries)} short presentations; {len(reviewed)} complete notices; {len(expected)} creatures covered.')

if __name__ == '__main__':
    main()
